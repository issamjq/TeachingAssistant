const DICTS = { en: EN, ar: AR };

// True when a quiz's output language reads right-to-left. Among the quiz
// languages only Arabic has a full dictionary + RTL layout here; the value
// arrives either as the code "ar" or the display name "Arabic".
export const isArabicLang = (lang) => lang === "ar" || lang === "Arabic";

// Translate a key into an EXPLICIT language, independent of the UI toggle.
// Used for exports (PDF / Word) where the worksheet titles must match the
// quiz's own language, not whatever the app is currently set to. Only en/ar
// dictionaries exist, so anything that isn't Arabic falls back to English.
export function tIn(lang, key, vars) {
  const dict = (isArabicLang(lang) ? DICTS.ar : DICTS.en) || EN;
  let s = dict[key];
  if (s == null) s = EN[key];
  if (s == null) return key;
  if (vars) {
    for (const [k, val] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(val));
    }
  }
  return s;
}

// ── Context ───────────────────────────────────────────────────────
const I18nContext = createContext({
  lang: "en",
  dir: "ltr",
  isRTL: false,
  setLang: () => {},
  t: (k) => k,
});

function applyDocumentLang(lang) {
  if (typeof document === "undefined") return;
  const dir = RTL_LANGS.has(lang) ? "rtl" : "ltr";
  document.documentElement.lang = lang;
  document.documentElement.dir = dir;
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    if (typeof localStorage === "undefined") return "en";
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === "ar" || saved === "en" ? saved : "en";
  });

  useEffect(() => { applyDocumentLang(lang); }, [lang]);

  const setLang = useCallback((next) => {
    const v = next === "ar" ? "ar" : "en";
    try { localStorage.setItem(STORAGE_KEY, v); } catch { /* ignore */ }
    setLangState(v);
  }, []);

  const t = useCallback(
    (key, vars) => {
      const dict = DICTS[lang] || EN;
      let s = dict[key];
      if (s == null) s = EN[key];
      if (s == null) return key;
      if (vars) {
        for (const [k, val] of Object.entries(vars)) {
          s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(val));
        }
      }
      return s;
    },
    [lang]
  );

  const dir = RTL_LANGS.has(lang) ? "rtl" : "ltr";
  const value = { lang, dir, isRTL: dir === "rtl", setLang, t };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
// Convenience: const t = useT();
export function useT() {
  return useContext(I18nContext).t;
}

// The BCP-47 tag to hand `toLocaleDateString` / `toLocaleTimeString`.
//
// Passing `undefined` uses the *browser's* locale, not the app's — so a
// teacher who switched Murchid to Arabic still got "Tuesday 4 August" from
// every date in the product. That is English leakage by another route, and it
// is invisible in code review because the call looks correct.
export const localeFor = (lang) => (isArabicLang(lang) ? "ar" : "en-US");

// Convenience: const locale = useLocale();
export function useLocale() {
  return localeFor(useContext(I18nContext).lang);
}

// Row statuses ("Draft", "In progress", "Scheduled") are free TEXT in
// Postgres, not an enum — they arrive as English strings written by whichever
// screen created the row. So translate by lookup, and fall back to the stored
// value: an unrecognised status must still render as itself rather than
// vanishing or showing a raw key.
export function useStatusLabel() {
  const t = useT();
  return (status) => {
    if (!status) return "";
    const key = `status.${String(status).toLowerCase().replace(/\s+/g, "-")}`;
    const translated = t(key);
    return translated === key ? status : translated;
  };
}

// ── Language toggle ───────────────────────────────────────────────
// Compact EN | ع pill. Drop it anywhere (sidebar, landing nav).
export function LangToggle({ className = "" }) {
  const { lang, setLang } = useI18n();
  const opts = [
    { v: "en", label: "EN" },
    { v: "ar", label: "ع" },
  ];
  return (
    <div
      className={`lang-toggle ${className}`}
      data-active={lang}
      role="group"
      aria-label="Language"
      dir="ltr"
    >
      {/* Sliding indicator rides under the active option. */}
      <span className="lang-toggle-ind" aria-hidden="true" />
      {opts.map((o) => (
        <button
          key={o.v}
          type="button"
          onClick={() => setLang(o.v)}
          className={`lang-toggle-opt${lang === o.v ? " is-active" : ""}`}
          aria-pressed={lang === o.v}
        >
          {o.label}
        </button>
      ))}
    </div>
  );
}
